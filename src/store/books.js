export const createBooksStore = (set) => ({
    ...initialState,
    setBookAction: (action) => set({ action }),
    setBookData: (bookData) => set({ bookData }),
    setBookQueryString: (bookQueryString) => set({ bookQueryString }),
    setBookResultsQueryString: (bookResultsQueryString) => set({ bookResultsQueryString }),
    setBookExpanded: (bookExpanded) => set({ bookExpanded }),
    setBookDateLimiter: (bookDateLimiter) => set({ bookDateLimiter }),
    setBookLimiter: (limiter) => set({ limiter }),
    setBookAppliedFacets: (bookAppliedFacets) => set({ bookAppliedFacets }),
    setBookFacets: (bookFacets) => set({ bookFacets}),
    reset: () => set({ ...initialState }),
    setBookHits: (bookHits) => set({ bookHits }),
    setBookSort: (bookSort) => set({ bookSort }),
    setBookSubjectHeadings: (bookSubjectHeadings) => set({ bookSubjectHeadings }),
    removeBookFacetAction: (facetAction) => {
        set((state) => ({
            bookAction: state.bookAction.filter(action => action !== facetAction),
        }))
    },
    setBookFacetAction: (bookFacetAction) => set({ bookFacetAction }),
    setBookPage: (bookPage) => set({ bookPage }),
    setBookTotalPages: (bookTotalPages) => set({ bookTotalPages }),
    setBookFieldCode: (bookFieldCode) => set({ bookFieldCode }),
    setBookRefine: (bookRefine) => set({ bookRefine }),
})